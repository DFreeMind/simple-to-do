function copyKey(copy) {
  return `${copy[0]}\u0000${copy[1]}`
}

export function getRhythmCopyCategory(reminder) {
  return RHYTHM_COPY_CATALOG[reminder?.id]
    ? reminder.id
    : (RHYTHM_COPY_CATALOG[reminder?.triggerType] ? reminder.triggerType : 'interval')
}

export function getRhythmCopyOptions(reminder) {
  const category = getRhythmCopyCategory(reminder)
  return RHYTHM_COPY_CATALOG[category].map(([title, message]) => ({ title, message, key: copyKey([title, message]) }))
}

export function pickRhythmCopy(reminder, excludedKeys = []) {
  const options = getRhythmCopyOptions(reminder)
  const excluded = new Set(excludedKeys)
  const candidates = options.filter(option => !excluded.has(option.key))
  const pool = candidates.length ? candidates : options
  return pool[Math.floor(Math.random() * pool.length)]
}
